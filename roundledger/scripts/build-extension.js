// Builds the unpacked extension into dist/extension and a zip next to it.
//   ROUNDLEDGER_BACKEND_URL=https://api.example.com npm run build:extension
// The backend URL must be https:// unless it points at localhost.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const version = pkg.version;
const backendUrl = (process.env.ROUNDLEDGER_BACKEND_URL || 'http://127.0.0.1:8787').replace(/\/$/, '');
const out = path.join(root, 'dist', 'extension');

const u = new URL(backendUrl);
const isLocal = ['127.0.0.1', 'localhost'].includes(u.hostname);
if (u.protocol !== 'https:' && !isLocal) {
  console.error(`Refusing to build: backend URL must use https:// (got ${backendUrl}).`);
  process.exit(1);
}
if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error('package.json version must be MAJOR.MINOR.PATCH');

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
const copy = (from, to) => fs.cpSync(path.join(root, from), path.join(out, to), { recursive: true });
copy('extension/src', 'src');
copy('extension/icons', 'icons');
fs.mkdirSync(path.join(out, 'shared/adapters'), { recursive: true });
for (const f of ['analysis.js', 'round-tracker.js']) copy(`shared/${f}`, `shared/${f}`);
for (const f of fs.readdirSync(path.join(root, 'shared/adapters'))) copy(`shared/adapters/${f}`, `shared/adapters/${f}`);

fs.writeFileSync(path.join(out, 'src/build-config.js'),
  `// Generated by scripts/build-extension.js — do not edit.\nexport const BUILD = Object.freeze(${JSON.stringify({ version, backendUrl, builtAt: new Date().toISOString() })});\n`);

const manifest = JSON.parse(fs.readFileSync(path.join(root, 'extension/manifest.template.json'), 'utf8'));
manifest.version = version;
manifest.host_permissions = [`${u.origin}/*`];
// Test builds only: pre-grant origins so automated UI tests need no permission prompt.
for (const o of (process.env.ROUNDLEDGER_TEST_HOST_PERMISSIONS || '').split(',').filter(Boolean)) manifest.host_permissions.push(o);
const keyFile = path.join(root, 'extension/extension-key.pub.b64');
let extensionId = null;
if (fs.existsSync(keyFile)) {
  manifest.key = fs.readFileSync(keyFile, 'utf8').trim();
  const digest = crypto.createHash('sha256').update(Buffer.from(manifest.key, 'base64')).digest('hex').slice(0, 32);
  extensionId = [...digest].map((c) => String.fromCharCode('a'.charCodeAt(0) + parseInt(c, 16))).join('');
}
fs.writeFileSync(path.join(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');

// ---- validation -----------------------------------------------------------
const problems = [];
const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else files.push(p);
  }
})(out);
for (const f of files.filter((f) => /\.(js|json|html|css)$/.test(f))) {
  const text = fs.readFileSync(f, 'utf8');
  const rel = path.relative(out, f);
  if (/AIza[0-9A-Za-z_-]{20,}/.test(text)) problems.push(`${rel}: looks like a Google API key`);
  if (/generativelanguage\.googleapis|x-goog-api-key/i.test(text)) problems.push(`${rel}: references the Gemini API directly (must go through the backend)`);
  if (/auto.?bet|placeBet|\.click\(\)/i.test(text)) problems.push(`${rel}: contains betting-automation terms`);
}
for (const ref of [manifest.background.service_worker, manifest.side_panel.default_path, ...Object.values(manifest.icons)]) {
  if (!fs.existsSync(path.join(out, ref))) problems.push(`manifest references missing file ${ref}`);
}
if (problems.length) {
  console.error('Build validation failed:\n  ' + problems.join('\n  '));
  process.exit(1);
}

// ---- checksums + zip ------------------------------------------------------
const sums = files.sort().map((f) => `${crypto.createHash('sha256').update(fs.readFileSync(f)).digest('hex')}  ${path.relative(out, f).split(path.sep).join('/')}`);
fs.writeFileSync(path.join(root, 'dist', 'extension.sha256'), sums.join('\n') + '\n');
const zip = path.join(root, 'dist', `roundledger-extension-${version}.zip`);
fs.rmSync(zip, { force: true });
execFileSync('zip', ['-qr', zip, '.'], { cwd: out });
fs.writeFileSync(path.join(root, 'dist', 'build-info.json'), JSON.stringify({ version, backendUrl, extensionId, files: files.length, builtAt: new Date().toISOString() }, null, 2) + '\n');
console.log(`Built extension ${version} → ${path.relative(root, out)} (${files.length} files)`);
console.log(`Backend: ${backendUrl}`);
if (extensionId) console.log(`Extension ID: ${extensionId}  (allow-list chrome-extension://${extensionId} in EXTENSION_ORIGINS)`);
console.log(`Zip: ${path.relative(root, zip)}`);
